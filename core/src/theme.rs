/// Resolve System to Black/White and return the matching table.
pub fn palette(skin: Skin) -> &'static Palette {
    match skin.resolve() {
        Skin::White => &WHITE,
        Skin::Blue => &BLUE,
        Skin::Green => &GREEN,
        Skin::Purple => &PURPLE,
        _ => &BLACK,
    }
}
